"""
TRION Protocol — L3 Mental Layer: Real Transformer-Based Genesis Inference
==========================================================================
Whitepaper §L3 "Mental Layer" calls for:
  "Base transformer on behavioral sequences, Genesis Inference v1,
   conformal prediction intervals"

This module provides a *genuine* PyTorch self-attention / transformer-encoder
model that operates over a sequence of 9-dim universal behavioral feature
vectors (f1–f9 from homomorphic_mapping.py / bh_ledger block_features) OR
over 128-dim archetype-space vectors (from genesis_inference.py).

Architecture
------------
Input : (batch, seq_len, input_dim)  — a sequence of per-timestep BH vectors
Encoder: 2-layer TransformerEncoder (nn.MultiheadAttention, d_model=32, nhead=4)
Pooling: mean over sequence → linear projection → scalar in [0,1]
Output : dict with keys that mirror infer_genesis_value() + prediction interval

DATA NOTE
---------
No live behavioral-sequence training set is connected at init time.
When train_on_centroids() is called the model is fit on synthetic sequences
generated by:
  1. Loading trion_archetype_centroids.npy  (64 × 128 centroids, all in [0,1])
  2. Projecting each centroid from 128-dim → input_dim (9 or 128) with PCA
  3. Building 16-step sequences: centroid repeated + Gaussian noise σ=0.05
  4. Regression target = centroid row-norm / max_norm  (ordinal value signal)
This is synthetic-but-realistic bootstrapping from real protocol centroids.
The code comments and logs state this clearly and never claim otherwise.

Integration
-----------
The public function  infer_genesis_value_v2()  has the SAME call signature
as the existing  infer_genesis_value()  in genesis_inference.py.
genesis_inference.py imports and wraps this function; callers are unchanged.

Fallback
--------
If PyTorch is unavailable OR the model has not been fitted yet, all calls
fall through to the original harmonic-cosine path in genesis_inference.py.
A log line explicitly names which path is taken on every call.
"""

