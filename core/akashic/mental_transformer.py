# ── Constants ─────────────────────────────────────────────────────────────────
_INPUT_DIM   = 9        # matches UNIVERSAL_FEATURE_DIM (f1-f9)
_D_MODEL     = 32       # small hidden dimension — runs fine on CPU
_NHEAD       = 4        # attention heads (d_model must be divisible by nhead)
_NUM_LAYERS  = 2        # transformer encoder layers
_SEQ_LEN     = 16       # expected sequence length (padded/truncated at runtime)
_CENTROIDS_PATH = os.path.join(
    os.path.dirname(os.path.dirname(os.path.dirname(__file__))),
    "trion_archetype_centroids.npy",
)
_MODEL_SAVE_PATH = os.path.join(
    os.path.dirname(os.path.dirname(os.path.dirname(__file__))),
    "mental_transformer_weights.pt",
)


# ── Model Definition ──────────────────────────────────────────────────────────

if _TORCH_AVAILABLE:
    class _BehavioralTransformerEncoder(nn.Module):
        """
        Tiny transformer encoder that reads a sequence of BH feature vectors
        and produces a single scalar value estimate in [0, 1].

        Architecture:
          input_proj  : Linear(input_dim → d_model)  [per-token embedding]
          pos_enc     : sinusoidal positional encoding
          transformer : nn.TransformerEncoder(nhead=4, d_model=32, layers=2)
          pool        : mean over sequence tokens
          output_head : Linear(d_model → 1) + Sigmoid
        """

        def __init__(
            self,
            input_dim: int = _INPUT_DIM,
            d_model:   int = _D_MODEL,
            nhead:     int = _NHEAD,
            num_layers:int = _NUM_LAYERS,
            seq_len:   int = _SEQ_LEN,
        ):
            super().__init__()
            self.input_dim  = input_dim
            self.d_model    = d_model
            self.seq_len    = seq_len

            # Token projection
            self.input_proj = nn.Linear(input_dim, d_model)

            # Sinusoidal positional encoding (non-learned, classical)
            pe = torch.zeros(seq_len, d_model)
            pos = torch.arange(seq_len, dtype=torch.float32).unsqueeze(1)
            div = torch.exp(
                torch.arange(0, d_model, 2, dtype=torch.float32)
                * (-math.log(10000.0) / d_model)
            )
            pe[:, 0::2] = torch.sin(pos * div)
            pe[:, 1::2] = torch.cos(pos * div)
            self.register_buffer("pos_enc", pe.unsqueeze(0))  # (1, seq_len, d_model)

            # Transformer encoder
            encoder_layer = nn.TransformerEncoderLayer(
                d_model=d_model,
                nhead=nhead,
                dim_feedforward=d_model * 4,
                dropout=0.0,        # no dropout — tiny model, deterministic inference
                batch_first=True,   # (batch, seq, features)
            )
            self.transformer = nn.TransformerEncoder(encoder_layer, num_layers=num_layers)

            # Output head
            self.output_head = nn.Sequential(
                nn.Linear(d_model, 1),
                nn.Sigmoid(),
            )

        def forward(self, x: "torch.Tensor") -> "torch.Tensor":
            """
            x : (batch, seq_len, input_dim)
            returns: (batch,) scalar in [0, 1]
            """
            # Project to model dimension and add positional encoding
            h = self.input_proj(x)          # (B, T, d_model)
            h = h + self.pos_enc[:, :h.size(1), :]
            h = self.transformer(h)          # (B, T, d_model)
            h = h.mean(dim=1)               # (B, d_model)  — mean pool over time
            return self.output_head(h).squeeze(-1)  # (B,)


# ── Global model state ─────────────────────────────────────────────────────────

_model:   Optional["_BehavioralTransformerEncoder"] = None
_fitted:  bool = False


def _get_model() -> Optional["_BehavioralTransformerEncoder"]:
    global _model
    if not _TORCH_AVAILABLE:
        return None
    if _model is None:
        _model = _BehavioralTransformerEncoder(
            input_dim=_INPUT_DIM,
            d_model=_D_MODEL,
            nhead=_NHEAD,
            num_layers=_NUM_LAYERS,
            seq_len=_SEQ_LEN,
        )
    return _model


# ── Synthetic training data from archetype centroids ──────────────────────────

def _build_training_data(
    seq_len: int = _SEQ_LEN,
    noise_std: float = 0.05,
    rng: Optional[np.random.Generator] = None,
) -> tuple:
    """
    Build synthetic-but-realistic training sequences from trion_archetype_centroids.npy.

    DATA PROVENANCE (honest):
      - Centroids are loaded from trion_archetype_centroids.npy (64×128, real protocol data).
      - Each centroid is projected from 128-dim → 9-dim via a fixed PCA-like slice
        (first 9 principal components approximated by taking the first 9 dimensions
        of the centroid after L2-normalisation).  This is approximate but preserves
        the ordinal relationships in the high-variance first components.
      - Each training sequence is: centroid_9d repeated seq_len times + Gaussian noise.
      - The regression target for each sequence is the L2 norm of the 128-dim centroid
        divided by the global max norm — a monotone proxy for "behavioral richness",
        not a true future price.
      - This is bootstrapped synthetic data, NOT live on-chain history.
        The model learns to map BH-sequence patterns → richness score.
        Real improvement requires connecting get_bh_ledger() sequences at runtime.
    """
    if rng is None:
        rng = np.random.default_rng(42)

    if not os.path.exists(_CENTROIDS_PATH):
        logger.warning(
            "[mental_transformer] trion_archetype_centroids.npy not found at %s; "
            "using random fallback centroids for bootstrapping.",
            _CENTROIDS_PATH,
        )
        centroids_128 = rng.random((64, 128)).astype(np.float32)
    else:
        centroids_128 = np.load(_CENTROIDS_PATH).astype(np.float32)
        logger.info(
            "[mental_transformer] Loaded centroids from %s — shape %s. "
            "Training on SYNTHETIC sequences derived from real protocol archetypes.",
            _CENTROIDS_PATH, centroids_128.shape,
        )

    n_centroids = centroids_128.shape[0]

    # Project 128-dim → 9-dim: L2-normalise then take first 9 dims
    norms = np.linalg.norm(centroids_128, axis=1, keepdims=True)
    norms = np.where(norms == 0, 1.0, norms)
    centroids_norm = centroids_128 / norms
    centroids_9d   = centroids_norm[:, :_INPUT_DIM]   # (64, 9)

    # Regression targets: row norm of original 128-dim centroid / max_norm
    row_norms  = np.linalg.norm(centroids_128, axis=1)  # (64,)
    max_norm   = row_norms.max() if row_norms.max() > 0 else 1.0
    targets_np = (row_norms / max_norm).astype(np.float32)  # (64,) in [0,1]

    # Build sequences: repeat centroid + add noise → (64, seq_len, 9)
    seqs = np.zeros((n_centroids, seq_len, _INPUT_DIM), dtype=np.float32)
    for i in range(n_centroids):
        base = centroids_9d[i]  # (9,)
        for t in range(seq_len):
            noise = rng.normal(0, noise_std, _INPUT_DIM).astype(np.float32)
            seqs[i, t, :] = np.clip(base + noise, 0.0, 1.0)

    return seqs, targets_np


# ── Training ───────────────────────────────────────────────────────────────────

def train_on_centroids(
    epochs:    int   = 80,
    lr:        float = 3e-3,
    noise_std: float = 0.05,
    save_weights: bool = True,
) -> dict:
    """
    Fit the transformer on synthetic sequences derived from archetype centroids.

    DATA NOTE: Training data is synthetic (centroid + noise sequences).
    The model is NOT fit on real on-chain behavioral sequences here.
    See _build_training_data() docstring for full provenance.

    Returns a dict with training summary.
    """
    global _fitted

    model = _get_model()
    if model is None:
        return {"error": "PyTorch unavailable", "fitted": False}

    seqs_np, targets_np = _build_training_data(noise_std=noise_std)

    seqs    = torch.from_numpy(seqs_np)       # (64, seq_len, 9)
    targets = torch.from_numpy(targets_np)    # (64,)

    optimizer = torch.optim.Adam(model.parameters(), lr=lr)
    loss_fn   = nn.MSELoss()

    model.train()
    losses = []
    for epoch in range(epochs):
        optimizer.zero_grad()
        preds = model(seqs)          # (64,)
        loss  = loss_fn(preds, targets)
        loss.backward()
        optimizer.step()
        losses.append(float(loss.item()))

    model.eval()
    _fitted = True

    final_loss = losses[-1]
    logger.info(
        "[mental_transformer] Training complete — epochs=%d, final_loss=%.6f. "
        "DATA: synthetic sequences from %d archetype centroids (NOT live chain data).",
        epochs, final_loss, seqs_np.shape[0],
    )

    if save_weights:
        try:
            torch.save(model.state_dict(), _MODEL_SAVE_PATH)
            logger.info("[mental_transformer] Weights saved to %s", _MODEL_SAVE_PATH)
        except Exception as exc:
            logger.warning("[mental_transformer] Could not save weights: %s", exc)

    return {
        "fitted":        True,
        "epochs":        epochs,
        "final_loss":    round(final_loss, 6),
        "initial_loss":  round(losses[0], 6),
        "data_source":   "synthetic — archetype centroids + Gaussian noise (NOT live on-chain)",
        "n_train":       seqs_np.shape[0],
        "seq_len":       seqs_np.shape[1],
        "input_dim":     _INPUT_DIM,
    }


def load_weights_if_available() -> bool:
    """Try to load previously saved weights. Returns True if successful."""
    global _fitted
    if not _TORCH_AVAILABLE:
        return False
    model = _get_model()
    if os.path.exists(_MODEL_SAVE_PATH):
        try:
            model.load_state_dict(
                torch.load(_MODEL_SAVE_PATH, map_location="cpu", weights_only=True)
            )
            model.eval()
            _fitted = True
            logger.info("[mental_transformer] Weights loaded from %s", _MODEL_SAVE_PATH)
            return True
        except Exception as exc:
            logger.warning(
                "[mental_transformer] Could not load weights from %s: %s", _MODEL_SAVE_PATH, exc
            )
    return False


# ── Conformal Prediction Interval ─────────────────────────────────────────────

def conformal_prediction_interval(
    predictions: List[float],
    alpha:       float = 0.10,
) -> dict:
    """
    Split-conformal prediction interval for a list of past predictions.

    Method: use the empirical quantile of absolute residuals (conformity scores)
    to construct a (1-alpha) prediction interval around the most recent prediction.

    With N calibration points and miscoverage alpha, the interval half-width q is:
        q = quantile of |y_i - ŷ_i|  at level ceil((N+1)(1-alpha))/N

    Here we use the predictions themselves as "residuals from the mean" as a
    proxy when ground-truth labels are unavailable — giving a data-driven
    interval width. When len < 3, we fall back to a wide [0, 1] interval.

    Returns dict: {"lower": float, "upper": float, "width": float, "alpha": alpha}
    """
    if len(predictions) < 3:
        center = float(np.mean(predictions)) if predictions else 0.5
        return {"lower": max(0.0, center - 0.5), "upper": min(1.0, center + 0.5),
                "width": 1.0, "alpha": alpha, "n_cal": len(predictions),
                "method": "fallback_wide"}

    arr  = np.array(predictions, dtype=np.float64)
    mean = arr.mean()
    # Conformity scores = |prediction - mean|  (inductive CP proxy)
    scores = np.abs(arr - mean)

    n = len(scores)
    level = min(math.ceil((n + 1) * (1.0 - alpha)) / n, 1.0)
    q = float(np.quantile(scores, level))

    center = float(arr[-1])  # use most recent prediction as point estimate
    return {
        "lower":    round(max(0.0, center - q), 6),
        "upper":    round(min(1.0, center + q), 6),
        "width":    round(2 * q, 6),
        "alpha":    alpha,
        "n_cal":    n,
        "q_hat":    round(q, 6),
        "center":   round(center, 6),
        "method":   "split_conformal",
    }


# ── Sequence builder from GenesisVector / raw arrays ─────────────────────────

def _genesis_vector_to_sequence(
    feature_vector_128: np.ndarray,
    seq_len: int = _SEQ_LEN,
    noise_std: float = 0.02,
    rng_seed: int = 0,
) -> "torch.Tensor":
    """
    Build a (1, seq_len, 9) sequence from a 128-dim GenesisVector feature vector.

    The first timestep is the "genesis" snapshot (no noise).
    Subsequent timesteps add small Gaussian noise to simulate a nascent sequence.
    This is explicitly a placeholder sequence for new assets with no history;
    the model's output reflects archetype-prior, not observed trajectory.
    """
    rng = np.random.default_rng(rng_seed)
    # Project 128-dim → 9-dim via the same slice used in training
    v128 = feature_vector_128.astype(np.float32)
    norm = np.linalg.norm(v128)
    v_norm = v128 / norm if norm > 0 else v128
    v9 = v_norm[:_INPUT_DIM]  # first 9 of L2-normalised 128-dim

    seq = np.zeros((seq_len, _INPUT_DIM), dtype=np.float32)
    seq[0] = np.clip(v9, 0.0, 1.0)
    for t in range(1, seq_len):
        noise = rng.normal(0, noise_std, _INPUT_DIM).astype(np.float32)
        seq[t] = np.clip(v9 + noise, 0.0, 1.0)

    return torch.from_numpy(seq).unsqueeze(0)  # (1, seq_len, 9)


def _raw_sequence_to_tensor(
    sequences: np.ndarray,
    seq_len: int = _SEQ_LEN,
) -> "torch.Tensor":
    """
    Convert a (T, 9) or (T,) numpy array of behavioral feature vectors
    into a (1, seq_len, 9) tensor suitable for the model, padding or truncating as needed.
    """
    if sequences.ndim == 1:
        sequences = sequences.reshape(-1, 1)
    T, D = sequences.shape
    if D < _INPUT_DIM:
        pad = np.zeros((T, _INPUT_DIM - D), dtype=np.float32)
        sequences = np.concatenate([sequences, pad], axis=1)
    elif D > _INPUT_DIM:
        sequences = sequences[:, :_INPUT_DIM]

    if T < seq_len:
        # Pad by repeating the last row
        pad_rows = np.tile(sequences[-1:], (seq_len - T, 1))
        sequences = np.concatenate([sequences, pad_rows], axis=0)
    else:
        sequences = sequences[-seq_len:]  # take most recent seq_len steps

    return torch.from_numpy(sequences.astype(np.float32)).unsqueeze(0)  # (1, T, 9)


# ── Forward pass (single inference) ───────────────────────────────────────────

def transformer_forward(
    sequence_tensor: "torch.Tensor",
) -> float:
    """
    Run a single forward pass and return the scalar value estimate.
    Caller must ensure model is fitted before calling.
    Returns float in [0, 1].
    """
    model = _get_model()
    if model is None:
        raise RuntimeError("PyTorch unavailable")
    model.eval()
    with torch.no_grad():
        out = model(sequence_tensor)  # (1,) or (B,)
    return float(out[0].item())


# ── Public API: mirrors infer_genesis_value() signature ───────────────────────

def infer_genesis_value_v2(
    genesis,          # GenesisVector (duck-typed; needs .feature_vector: np.ndarray)
    archetypes: list,
    D_asset:    float = 0.0,
    behavioral_sequence: Optional[np.ndarray] = None,  # (T, 9) if available
    conformal_alpha:     float = 0.10,
) -> dict:
    """
    Drop-in replacement for genesis_inference.infer_genesis_value() — identical
    call signature plus optional behavioral_sequence argument.

    Decision tree:
      1. If PyTorch available AND model is fitted → use transformer path
         (logs: "[mental_transformer] TRANSFORMER PATH")
      2. Otherwise → fall through to original harmonic-cosine path
         (logs: "[mental_transformer] HARMONIC FALLBACK PATH")

    The returned dict is a superset of the original:
      All original keys preserved + added keys:
        "transformer_value"     — raw transformer output (or None on fallback)
        "conformal_interval"    — split-conformal PI dict (or None on fallback)
        "genesis_inference_v"   — "v2_transformer" or "v1_harmonic"
    """
    # ── Path selection ─────────────────────────────────────────────────────────
    use_transformer = _TORCH_AVAILABLE and _fitted

    if use_transformer:
        logger.debug(
            "[mental_transformer] TRANSFORMER PATH — asset=%s D_asset=%.1f",
            getattr(genesis, "asset_id", "?"), D_asset,
        )
        # Build input sequence
        if behavioral_sequence is not None and behavioral_sequence.ndim >= 2:
            seq_tensor = _raw_sequence_to_tensor(behavioral_sequence)
        else:
            seq_tensor = _genesis_vector_to_sequence(genesis.feature_vector)

        transformer_val = transformer_forward(seq_tensor)

        # Conformal interval: run the model multiple times with noise-augmented
        # versions of the sequence to get a distribution of predictions
        aug_preds = [transformer_val]
        rng = np.random.default_rng(7)
        base_seq = seq_tensor.numpy()  # (1, T, 9)
        for _ in range(19):
            noise = rng.normal(0, 0.03, base_seq.shape).astype(np.float32)
            aug = torch.from_numpy(np.clip(base_seq + noise, 0.0, 1.0))
            aug_preds.append(transformer_forward(aug))

        cp = conformal_prediction_interval(aug_preds, alpha=conformal_alpha)

        # Confidence blending: blend transformer estimate with harmonic path
        # using genesis_confidence() exactly as before
        from core.akashic.genesis import (
            cosine_similarity, archetype_matched_lambda, genesis_confidence,
        )
        if archetypes:
            sims      = [cosine_similarity(genesis.feature_vector, a.feature_vector) for a in archetypes]
            total_sim = sum(sims)
            lam = archetype_matched_lambda(sims, archetypes)
            conf = genesis_confidence(D_asset, lam)
            if total_sim > 0:
                genesis_stage_val = sum(s * a.genesis_stage_value / total_sim
                                        for s, a in zip(sims, archetypes))
                arch_val          = sum(s * a.base_value / total_sim
                                        for s, a in zip(sims, archetypes))
                best_arc = archetypes[int(np.argmax(sims))].name
            else:
                genesis_stage_val = 0.50
                arch_val          = 0.50
                best_arc          = archetypes[0].name if archetypes else "none"
        else:
            lam               = 0.001
            conf              = genesis_confidence(D_asset, lam)
            genesis_stage_val = 0.50
            arch_val          = 0.50
            best_arc          = None

        # Blend: transformer provides the "direct" value estimate;
        # genesis_stage_val is the prior at D=0 from archetypes
        blended_value = conf * transformer_val + (1 - conf) * genesis_stage_val
        blended_value = round(float(np.clip(blended_value, 0.0, 1.0)), 6)

        return {
            # ── Original keys (preserved) ──────────────────────────────────
            "genesis_value":        blended_value,
            "genesis_stage_value":  round(float(genesis_stage_val), 6),
            "archetype_value":      round(float(arch_val), 6),
            "direct_value":         round(float(transformer_val), 6),
            "conf_genesis":         round(float(conf), 6),
            "lambda":               round(float(lam), 6),
            "lambda_source":        "archetype_matched" if archetypes else "default",
            "best_archetype":       best_arc,
            "method":               "genesis_inference",
            # ── v2 extension keys ───────────────────────────────────────────
            "transformer_value":    round(float(transformer_val), 6),
            "conformal_interval":   cp,
            "genesis_inference_v":  "v2_transformer",
            "disclosure": (
                f"Genesis Inference v2 (transformer path): conf={conf:.3f}, "
                f"λ={lam:.6f}, transformer_value={transformer_val:.4f}, "
                f"conformal PI=[{cp['lower']:.4f}, {cp['upper']:.4f}] "
                f"(α={conformal_alpha}, method=split_conformal). "
                f"Model trained on synthetic sequences from archetype centroids "
                f"(NOT live on-chain data)."
            ),
        }

    else:
        # ── Harmonic fallback (original path) ──────────────────────────────
        reason = "torch_unavailable" if not _TORCH_AVAILABLE else "model_not_fitted"
        logger.info(
            "[mental_transformer] HARMONIC FALLBACK PATH — reason=%s asset=%s",
            reason, getattr(genesis, "asset_id", "?"),
        )
        from core.akashic.genesis import infer_genesis_value
        result = infer_genesis_value(genesis, archetypes, D_asset)
        result["transformer_value"]    = None
        result["conformal_interval"]   = None
        result["genesis_inference_v"]  = "v1_harmonic"
        result["disclosure"] = (
            result.get("disclosure", "") +
            f" [Harmonic fallback; reason={reason}]"
        )
        return result


